const {test,expect}=require('@playwright/test')
test.use({launchOptions:{executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--no-sandbox']}})
const base=process.env.SEO_TEST_BASE_URL||'http://localhost:3035'
for(const [width,theme] of [[320,'light'],[390,'dark'],[1440,'light']])test(`complete footer at ${width}px ${theme}`,async({page})=>{
 const errors=[]
 page.on('console',message=>{if(message.type()==='error'&&/hydrat|server rendered HTML/i.test(message.text()))errors.push(message.text())})
 page.on('pageerror',error=>errors.push(error.message))
 await page.addInitScript(({theme,base})=>{if(location.origin!==new URL(base).origin)return;sessionStorage.setItem('leadPopupShown','true');localStorage.setItem('visionsecure-theme',theme)},{theme,base})
 await page.route('**/*',route=>new URL(route.request().url()).origin===base&&route.request().method()==='GET'?route.continue():route.abort())
 await page.setViewportSize({width,height:900})
 await page.goto(base)
 await expect(page.getByRole('button',{name:'CCTV',exact:true})).toBeEnabled()
 const footer=page.locator('footer')
 await expect(footer.getByRole('navigation',{name:'Footer company'}).getByRole('link')).toHaveCount(6)
 await expect(footer.getByRole('navigation',{name:'Footer support'}).getByRole('link')).toHaveCount(4)
 const expected=[['Security & Surveillance',4],['Networking & IT',4],['Smart Technology & Safety',5]]
 for(const [label,count] of expected)await expect(footer.getByRole('navigation',{name:'Footer '+label}).getByRole('link')).toHaveCount(count)
 const urls=await footer.locator('a[href^="/services/"]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('href')))
 expect(urls).toHaveLength(13);expect(new Set(urls).size).toBe(13)
 await expect(footer.getByRole('link',{name:'Blogs',exact:true})).toHaveAttribute('href','/blog')
 await expect(footer.getByRole('link',{name:'Contact Us',exact:true})).toHaveAttribute('href','/contact')
 await expect(footer.getByRole('link',{name:'WhatsApp Us',exact:true})).toHaveAttribute('href','https://wa.me/919872133840')
 await expect(footer.getByRole('link',{name:'Call Us',exact:true})).toHaveAttribute('href','tel:+919872133840')
 await footer.scrollIntoViewIfNeeded()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
 await footer.getByRole('link',{name:'Request a Quote',exact:true}).focus()
 expect(await page.evaluate(()=>document.activeElement.getAttribute('href'))).toBe('/contact')
 await page.screenshot({path:`docs/seo/screenshots/footer-${width}-${theme}.png`,fullPage:false,animations:'disabled'})
 expect(errors).toEqual([])
})
